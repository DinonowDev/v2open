#!/usr/bin/env bash
# Print identity lines for bundled macOS engines (stdout → binaries/macos/VERSIONS).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/binaries/macos"

line() {
  local name="$1"
  local path="$DIR/$name"
  printf '%s\t' "$name"
  if [[ ! -f "$path" ]]; then
    echo "MISSING"
    return
  fi
  local arch
  arch="$(file -b "$path" 2>/dev/null | tr '\n' ' ')"
  local ver="(no version flag)"
  case "$name" in
    sing-box|sing-box.official)
      ver="$("$path" version 2>/dev/null | head -n 1 || true)"
      ;;
    xray)
      ver="$("$path" version 2>/dev/null | head -n 1 || true)"
      ;;
    *)
      ver="$(basename "$path") $(stat -f%z "$path" 2>/dev/null || stat -c%s "$path" 2>/dev/null) bytes"
      ;;
  esac
  printf '%s\t%s\n' "${ver:-unknown}" "$arch"
}

echo "# generated by scripts/binaries-versions.sh — do not hand-edit"
echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
for name in sing-box sing-box.official xray dnstt-client masterdns pingtunnel geoip.dat geosite.dat; do
  line "$name"
done
